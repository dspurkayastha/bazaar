/**
 * The tools exposed to the model. There is deliberately NO pay tool: `propose_checkout` builds a PolicyContext
 * and hands it to policy/gate.ts, which is the only code that may call Supplier.place.
 *
 * Rules enforced here, in code, regardless of what the model says:
 *  - the place is the resolver's answer; no tool takes a placeId,
 *  - the payment method comes from the run (request/household default), never from the model,
 *  - supplier text is sanitised before it reaches the model; stripped text is logged and reported,
 *  - build_cart only accepts variants the model has actually been shown in this run,
 *  - no tool throws into the model: every failure comes back as { ok: false, error }.
 */
