/** Shared by the tool and by the loop's end-of-run fallback. Never throws. */
export async function proposeCheckoutFor(env: ToolEnv, supplierId?: string, quoteHash?: string): Promise<Json> {
  const { state } = env;
  try {
    let quote: Quote | undefined;
    if (quoteHash !== undefined) {
      quote = [...state.quotes.values()].find((q) => q.hash === quoteHash);
      if (!quote)
        return {
          ok: false,
          status: 'ERROR',
          error: 'quoteHash is not a quote built in this request; call build_cart.',
        };
    } else if (supplierId !== undefined) {
      quote = state.quotes.get(pickOne(env, supplierId).id);
    } else if (state.quotes.size === 1) {
      quote = [...state.quotes.values()][0];
    } else if (state.quotes.size > 1) {
      return { ok: false, status: 'ERROR', error: 'More than one quote was built; pass supplier or quoteHash.' };
    }
    if (!quote) return { ok: false, status: 'ERROR', error: 'No cart has been built yet; call build_cart first.' };
    if (quote.lines.length === 0)
      return { ok: false, status: 'ERROR', error: 'The built cart is empty; nothing to check out.' };

    const supplier = env.suppliers.find((s) => s.id === quote.supplierId);
    if (!supplier)
      return { ok: false, status: 'ERROR', error: `${quote.supplierId} does not serve ${env.place.nickname}.` };

    const now = env.now();
    state.proposed = true;
    state.chosen = quote;
    try {
      const res = await placeWithGate({
        supplier,
        payment: env.payment,
        recorder: env.store.recorder,
        ...(env.store.gateLock ? { lock: env.store.gateLock } : {}),
        // Spend and approvals are loaded inside the gate lock.
        ctxBuilder: loadingContextBuilder(env.store, {
          household: env.household,
          place: env.place,
          quote,
          requestingMember: env.member,
          now,
          ...(env.webhook ? { webhook: env.webhook, approvals: false } : {}),
        }),
      });
      state.decision = res.decision;
      state.order = res.order;
      state.gateLine = gateLine({ decision: res.decision, quote, order: res.order, payment: env.payment });
      return {
        ok: true,
        status: 'PLACED',
        orderId: res.order.supplierOrderId,
        orderStatus: res.order.status,
        // Idempotent replay: this exact quote was already placed; nothing new was sent to the store.
        ...(res.replayed ? { alreadyPlaced: true } : {}),
        total: quote.total,
        totalInr: formatINR(quote.total),
        payment: env.payment.kind,
        gateLine: state.gateLine,
      };
    } catch (err) {
      if (err instanceof PolicyHold) {
        state.decision = err.decision;
        state.gateLine = gateLine({ decision: err.decision, quote, payment: env.payment });
        return {
          ok: true,
          status: 'HOLD',
          reasons: err.decision.reasons,
          quoteHash: err.quoteHash,
          approvalNeededFrom: 'an owner of the household, on this exact quote hash',
          gateLine: state.gateLine,
        };
      }
      if (err instanceof PolicyBlock) {
        state.decision = err.decision;
        state.gateLine = gateLine({ decision: err.decision, quote, payment: env.payment });
        return {
          ok: true,
          status: 'BLOCK',
          reasons: err.decision.reasons,
          quoteHash: err.quoteHash,
          requote: needsRequote(err),
          gateLine: state.gateLine,
        };
      }
      const message = err instanceof BazaarError || err instanceof Error ? err.message : String(err);
      // A failed place() may still have created an order; never advise a retry of checkout.
      state.gateLine = `Gate: ERROR — ${sanitiseField(message, 'gate.error', env.sanitiseLog, 'unknown error')}; check the store app before trying again.`;
      return {
        ok: false,
        status: 'ERROR',
        error: sanitiseField(message, 'gate.error', env.sanitiseLog),
        gateLine: state.gateLine,
      };
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    state.gateLine = `Gate: ERROR — ${message}.`;
    return { ok: false, status: 'ERROR', error: message, gateLine: state.gateLine };
  }
}

const askUser: ToolDef = {
  spec: {
    name: 'ask_user',
    description:
      'Ask the user questions and stop. Batch ALL questions into one call. Only for: out-of-stock with no equivalent, an unusual quantity, or a genuinely ambiguous item. Ends the request; the user answers in a new message.',
    input_schema: {
      type: 'object',
      properties: { questions: { type: 'array', items: { type: 'string' }, minItems: 1, maxItems: 5 } },
      required: ['questions'],
    },
  },
  async run(input, env) {
    const i = obj(input);
    if (!Array.isArray(i.questions) || i.questions.length === 0 || i.questions.length > 5) {
      throw new ToolInputError('questions must be an array of 1 to 5 strings');
    }
    const qs = i.questions.map((q, n) => str(q, `questions[${n}]`, 300));
    env.state.questions.push(...qs);
    env.state.stop = true;
    return {
      ok: true,
      note: 'Questions queued. The request ends here; write one short sentence saying you are waiting for the answers.',
    };
  },
};

