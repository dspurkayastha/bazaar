export const MAX_LINES = 40;
export const MAX_LINE_QUANTITY = 99;
const MAX_SEARCH_RESULTS = 8;
export const MAX_SEARCH_MANY_QUERIES = 12;
const MAX_SEARCH_MANY_RESULTS = 5;

/** Mutable per-request state the tools share with the loop. */
export interface RunState {
  /** Latest raw (hashed) quote per supplier built in this run. */
  quotes: Map<SupplierId, Quote>;
  /** Cart each supplier held before this request touched it. */
  existingCarts: Map<SupplierId, Quote>;
  /** Variants the model has been shown (search, go_to_items, read_cart, existing cart). */
  seenVariants: Set<string>;
  questions: string[];
  proposed: boolean;
  chosen?: Quote;
  decision?: PolicyDecision;
  order?: PlacedOrder;
  /** One line describing the gate outcome, always generated by code. */
  gateLine?: string;
  /** Set when the loop should stop calling the model (ask_user). */
  stop: boolean;
}

export function newRunState(): RunState {
  return {
    quotes: new Map(),
    existingCarts: new Map(),
    seenVariants: new Set(),
    questions: [],
    proposed: false,
    stop: false,
  };
}

export interface ToolEnv {
  request: ShopRequest;
  household: Household;
  member: Member;
  place: Place;
  resolution: PlaceResolution;
  /** Suppliers that deliver to `place`. */
  suppliers: Supplier[];
  store: Store;
  now: () => string;
  /** From the request / household default (cod for v1). The model cannot change it. */
  payment: PaymentMethod;
  sanitiseLog: SanitiseLog;
  state: RunState;
  /** Set for webhook-originated requests: no approvals, HOLD unless the channel is trusted (PolicyContext.webhook). */
  webhook?: PolicyContext['webhook'];
}

type Json = Record<string, unknown>;
export type ToolResult = Json & { ok: boolean };

interface ToolDef {
  spec: ToolSpec;
  /** Safe to run concurrently with other read-only calls from the same model turn (no cart/gate/question state). */
  readOnly?: boolean;
  run(input: unknown, env: ToolEnv): Promise<Json>;
}

// ---------- helpers ----------

class ToolInputError extends Error {}

function obj(input: unknown): Json {
  if (typeof input !== 'object' || input === null || Array.isArray(input))
    throw new ToolInputError('input must be an object');
  return input as Json;
}

function str(v: unknown, name: string, max = 200): string {
  if (typeof v !== 'string' || v.trim() === '') throw new ToolInputError(`${name} must be a non-empty string`);
  if (v.length > max) throw new ToolInputError(`${name} is too long (max ${max})`);
  return v.trim();
}

function optStr(v: unknown, name: string): string | undefined {
  return v === undefined || v === null ? undefined : str(v, name);
}

function pickSuppliers(env: ToolEnv, id: string | undefined): Supplier[] {
  if (id === undefined) return env.suppliers;
  const s = env.suppliers.find((x) => x.id === id);
  if (!s)
    throw new ToolInputError(
      `supplier must be one of: ${env.suppliers.map((x) => x.id).join(', ') || '(none serve this place)'}`,
    );
  return [s];
}

function pickOne(env: ToolEnv, id: string | undefined): Supplier {
  const list = pickSuppliers(env, id);
  if (list.length !== 1) {
    throw new ToolInputError(`supplier is required; one of: ${env.suppliers.map((x) => x.id).join(', ')}`);
  }
  return list[0]!;
}

function productView(p: SupplierProduct) {
  return {
    supplier: p.supplierId,
    productId: p.productId,
    name: p.name,
    ...(p.brand !== undefined ? { brand: p.brand } : {}),
    category: p.category,
    variants: p.variants.map((v) => ({
      variantId: v.variantId,
      label: v.label,
      price: v.price,
      priceInr: formatINR(v.price),
      mrp: v.mrp,
      inStock: v.inStock,
      ...(v.maxQuantity !== undefined ? { maxQuantity: v.maxQuantity } : {}),
      ...(v.unitPrice !== undefined ? { unitPrice: v.unitPrice } : {}),
    })),
  };
}

function showProducts(products: SupplierProduct[], env: ToolEnv, limit = MAX_SEARCH_RESULTS) {
  const clean = products.slice(0, limit).map((p) => sanitiseProduct(p, env.sanitiseLog));
  for (const p of clean) for (const v of p.variants) env.state.seenVariants.add(v.variantId);
  return clean.map(productView);
}

/** The model's view of a quote: sanitised text, same hash. Never re-hashed. */
export function quoteView(raw: Quote, env: Pick<ToolEnv, 'sanitiseLog' | 'place'>) {
  const q = sanitiseQuoteForModel(raw, env.sanitiseLog);
  return {
    supplier: q.supplierId,
    place: env.place.nickname,
    quoteHash: q.hash,
    lines: q.lines.map((l) => ({
      ...(l.itemKey !== undefined ? { itemKey: l.itemKey } : {}),
      variantId: l.variantId,
      name: l.name,
      label: l.label,
      quantity: l.quantity,
      unitPrice: l.unitPrice,
      lineTotal: l.lineTotal,
      category: l.category,
    })),
    itemTotal: q.itemTotal,
    fees: q.fees,
    total: q.total,
    totalInr: formatINR(q.total),
    ...(q.etaMinutes !== undefined ? { etaMinutes: q.etaMinutes } : {}),
    unavailable: q.unavailable,
  };
}

// ---------- gate line (always generated by code) ----------

export function gateLine(args: {
  decision: PolicyDecision;
  quote: Quote;
  order?: PlacedOrder;
  payment: PaymentMethod;
}): string {
  const { decision, quote, order, payment } = args;
  // On BLOCK, lead with the rules that blocked; the HOLD-level breaches that came along are secondary.
  const blocking = new Set(['quote_mismatch', 'category_blocked', 'unit_price_blocked']);
  const ordered =
    decision.verdict === 'BLOCK'
      ? [...decision.reasons].sort((a, b) => Number(blocking.has(b.rule)) - Number(blocking.has(a.rule)))
      : decision.reasons;
  const rules = [...new Set(ordered.map((r) => r.rule))].join(', ');
  const detail = ordered
    .slice(0, 2)
    .map((r) => r.detail)
    .join('; ');
  switch (decision.verdict) {
    case 'PAY': {
      const how = payment.kind === 'cod' ? 'cash on delivery' : payment.kind;
      const covered = decision.approvalId ? 'owner approval used' : 'within unattended limits';
      return `Gate: PAY (${covered}) — ${formatINR(quote.total)} placed by ${how}${order ? `, order ${order.supplierOrderId}` : ''}.`;
    }
    case 'HOLD':
      return `Gate: HOLD (${rules}) — ${detail}; an owner must approve quote ${quote.hash.slice(0, 12)} before it is placed.`;
    case 'BLOCK':
      return `Gate: BLOCK (${rules}) — ${detail}; not placed${decision.reasons.some((r) => r.rule === 'quote_mismatch') ? ', the cart changed and must be re-quoted' : ', no approval can unlock this'}.`;
  }
}

export function gateLineNotRun(reason: string): string {
  return `Gate: not run — ${reason}.`;
}

