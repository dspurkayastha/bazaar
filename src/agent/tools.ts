const readCart: ToolDef = {
  readOnly: true,
  spec: {
    name: 'read_cart',
    description: 'Read the live supplier cart for the delivery place.',
    input_schema: { type: 'object', properties: { supplier: supplierProp } },
  },
  async run(input, env) {
    const i = obj(input);
    const carts = [];
    for (const s of pickSuppliers(env, optStr(i.supplier, 'supplier'))) {
      const q = await s.readCart(env.place);
      for (const l of q.lines) env.state.seenVariants.add(l.variantId);
      carts.push(quoteView(q, env));
    }
    return { ok: true, carts };
  },
};

const REASON_KINDS = ['asked', 'recipe', 'default', 'member_add', 'usual'] as const;

function parseLines(raw: unknown, env: ToolEnv): CartLine[] {
  if (!Array.isArray(raw) || raw.length === 0) throw new ToolInputError('lines must be a non-empty array');
  if (raw.length > MAX_LINES) throw new ToolInputError(`too many lines (max ${MAX_LINES})`);
  return raw.map((entry, idx): CartLine => {
    const l = obj(entry);
    const variantId = str(l.variantId, `lines[${idx}].variantId`, 200);
    if (!env.state.seenVariants.has(variantId)) {
      throw new ToolInputError(
        `lines[${idx}].variantId ${variantId} was not returned by search, go_to_items or read_cart in this request; search first`,
      );
    }
    const quantity = l.quantity;
    if (typeof quantity !== 'number' || !Number.isInteger(quantity) || quantity < 1 || quantity > MAX_LINE_QUANTITY) {
      throw new ToolInputError(`lines[${idx}].quantity must be an integer from 1 to ${MAX_LINE_QUANTITY}`);
    }
    const r = obj(l.reason);
    const kind = r.kind;
    if (typeof kind !== 'string' || !(REASON_KINDS as readonly string[]).includes(kind)) {
      throw new ToolInputError(`lines[${idx}].reason.kind must be one of ${REASON_KINDS.join(', ')}`);
    }
    const itemKey = optStr(r.itemKey, `lines[${idx}].reason.itemKey`);
    return {
      variantId,
      quantity,
      reason: {
        kind: kind as CartLine['reason']['kind'],
        by: env.member.id, // always the requester; the model does not attribute lines to other people
        ...(itemKey !== undefined ? { itemKey } : {}),
      },
    };
  });
}

export type BuildCartErrorKind = 'supplier' | 'quote_mismatch' | 'invalid_line';

function buildCartError(kind: BuildCartErrorKind, message: string, env: ToolEnv): Json {
  const clean =
    kind === 'invalid_line' ? message : sanitiseField(message, 'build_cart.error', env.sanitiseLog, 'unreadable error');
  return { ok: false, error: { kind, message: clean } };
}

const buildCart: ToolDef = {
  spec: {
    name: 'build_cart',
    description:
      'Replace the supplier cart with exactly these lines and return the priced quote (with its hash). Send the COMPLETE desired cart in one call; any line not listed is removed. Every line needs a reason. Only variantIds returned by search/go_to_items/read_cart are accepted.',
    input_schema: {
      type: 'object',
      properties: {
        supplier: supplierProp,
        lines: {
          type: 'array',
          items: {
            type: 'object',
            properties: {
              variantId: { type: 'string' },
              quantity: { type: 'integer', minimum: 1, maximum: MAX_LINE_QUANTITY },
              reason: {
                type: 'object',
                properties: {
                  kind: { type: 'string', enum: [...REASON_KINDS] },
                  itemKey: { type: 'string', description: 'Profile item key this line satisfies, e.g. "milk".' },
                },
                required: ['kind'],
              },
            },
            required: ['variantId', 'quantity', 'reason'],
          },
        },
      },
      required: ['lines'],
    },
  },
  async run(input, env) {
    // Failures come back as { ok: false, error: { kind, message } } so the loop can tell repeats apart.
    let supplier: Supplier;
    let lines: CartLine[];
    try {
      const i = obj(input);
      supplier = pickOne(env, optStr(i.supplier, 'supplier'));
      lines = parseLines(i.lines, env);
    } catch (err) {
      return buildCartError('invalid_line', err instanceof Error ? err.message : String(err), env);
    }
    try {
      const quote = await supplier.quote(lines, env.place);
      await env.store.saveQuote(env.household.id, quote, env.request.id);
      env.state.quotes.set(supplier.id, quote);
      // A new cart invalidates any earlier proposal for this supplier.
      env.state.proposed = false;
      return { ok: true, quote: quoteView(quote, env) };
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      return buildCartError(err instanceof QuoteMismatch ? 'quote_mismatch' : 'supplier', message, env);
    }
  },
};

